/** 规则覆盖的组织全集:范围表只对澧水组织体系有约束力。
 *  不在全集内的组织(用户自建组织、存量迁移节点 01040404 等)没有适用范围依据,按无限制处理,
 *  否则这些组织下所有科目都会被误判为不可见/不可录入。 */
const ACCOUNT_SCOPE_ENTRIES = Object.entries(ACCOUNT_ORG_SCOPE);
const ACCOUNT_SCOPE_BY_CODE = new Map(ACCOUNT_SCOPE_ENTRIES);
const ACCOUNT_SCOPE_PREFIXES = ACCOUNT_SCOPE_ENTRIES
  .map(([code]) => code)
  .sort((a, b) => b.length - a.length || a.localeCompare(b));
const SCOPE_ORG_UNIVERSE = new Set(ACCOUNT_SCOPE_ENTRIES.flatMap(([, orgCodes]) => orgCodes));

/**
 * 判定科目在给定的组织末级范围中是否可见
 * @param accountCode 科目编码
 * @param scopeLeafOrgCodes 当前选中的组织所包含的末级组织编码集合(Set<string>)
 * @returns boolean
 */
export function isAccountVisibleForScope(
  accountCode: string,
  scopeLeafOrgCodes: Set<string> | undefined
): boolean {
  if (!scopeLeafOrgCodes || scopeLeafOrgCodes.size === 0) return true;

  // 范围内的组织均不在规则全集内:无适用范围依据,视为无限制
  let scopeKnown = false;
  for (const c of scopeLeafOrgCodes) {
    if (SCOPE_ORG_UNIVERSE.has(c)) { scopeKnown = true; break; }
  }
  if (!scopeKnown) return true;

  // 1. 精确匹配
  const exact = ACCOUNT_SCOPE_BY_CODE.get(accountCode);
  if (exact) {
    return exact.some((c) => scopeLeafOrgCodes.has(c));
  }

  // 2. 前缀继承必须取最长(最具体)匹配，不受对象插入顺序影响。
  // 例如 I11031 同时匹配 I11 与 I1103 时，应继承 I1103 的水电专属范围。
  const prefix = ACCOUNT_SCOPE_PREFIXES.find((code) => accountCode.length > code.length && accountCode.startsWith(code));
  if (prefix) return (ACCOUNT_SCOPE_BY_CODE.get(prefix) ?? []).some((c) => scopeLeafOrgCodes.has(c));

  // 通用科目(未限定者)对所有组织可见
  return true;
}
